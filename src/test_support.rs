//! テスト全体で共有するユーティリティ。
//!
//! 複数のテストモジュール(`init`・`state` など)が、プロセス全体で共有される
//! `HOME` 環境変数を書き換える。各モジュールがそれぞれローカルに `Mutex` を持つと
//! ファイルをまたいだ排他が効かず、別ファイルのテストが同時に `HOME` を書き換えて
//! 取り違える(例: `state` のマイグレーションテストと `init` のテストが並行実行で
//! 競合し、状態ファイルのパスがずれて間欠的に失敗する)。
//!
//! そのため、共有環境変数を操作する全テストで使う単一のグローバルロックをここに
//! 集約する。

use std::sync::{Mutex, MutexGuard, OnceLock};

/// `HOME` など、プロセス全体で共有される環境変数を書き換えるテスト用のグローバル
/// ロックを取得する。
///
/// 共有環境変数を操作する全テストはこのロックを取得して直列化すること。ロック保持中
/// のテストが panic してロックが poison しても、後続テストが巻き添えで失敗しないよう
/// poison を無視して内側のガードを返す。各テストは利用前に `HOME` を自分の一時
/// ディレクトリへ設定し直すため、汚染された状態を引き継いでも問題ない。
pub(crate) fn lock_env() -> MutexGuard<'static, ()> {
    static LOCK: OnceLock<Mutex<()>> = OnceLock::new();
    LOCK.get_or_init(|| Mutex::new(()))
        .lock()
        .unwrap_or_else(|poisoned| poisoned.into_inner())
}
